print("คำนวณ BMI และเเปลผลสุขภาพ\n")

hight = float(input("กรุณาใส่ความสูงของคุณ (เมตร)"))
weight = float(input("กรุณาใส่น้ำหนักของคุณ (กิโลกรัม)"))

bmi = weight / (hight * hight) 

print(F"\nค่าดัชนีมวลกาย (BMI) ของคุณคือ: {bmi:.2F}")
if bmi < 18.5:
   print("น้ำหนักคุณน้อยกว่าเกณฑ์")
elif 18.5 <= bmi <22.9:
   print("น้ำหนักคุณอยู่ในเกณฑ์ปกติ")
elif 23 <= bmi < 24.9: 
   print("น้ำหนักคุณในเกณฑ์หนักเกิน")
else:
     print("คุณอยู่ในเกณฑ์อ้วน")